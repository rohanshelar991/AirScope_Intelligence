#!/usr/bin/env node
/**
 * Generate public/config.js with the OpenWeather API key from env.
 * Falls back to placeholder to avoid committing secrets.
 */
const fs = require('fs');
const path = require('path');

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }

  return fs
    .readFileSync(filePath, 'utf8')
    .split(/\r?\n/)
    .filter((line) => line && !line.trim().startsWith('#') && line.includes('='))
    .reduce((env, line) => {
      const [envKey, ...valueParts] = line.split('=');
      env[envKey.trim()] = valueParts.join('=').trim();
      return env;
    }, {});
}

const appRoot = path.join(__dirname, '..');
const localEnv = parseEnvFile(path.join(appRoot, '.env.local'));
const baseEnv = parseEnvFile(path.join(appRoot, '.env'));

const key =
  process.env.REACT_APP_OPENWEATHER_API_KEY ||
  localEnv.REACT_APP_OPENWEATHER_API_KEY ||
  localEnv.OPENWEATHER_API_KEY ||
  baseEnv.REACT_APP_OPENWEATHER_API_KEY ||
  baseEnv.OPENWEATHER_API_KEY ||
  'YOUR_API_KEY';
const outPath = path.join(appRoot, 'public', 'config.js');

const contents = `// Auto-generated by scripts/generate-config.js
// Replace with a valid OpenWeather API key at build time.
window.__OPENWEATHER_API_KEY__ = '${key}';
`;

fs.writeFileSync(outPath, contents, 'utf8');
console.log(`Generated public/config.js with key=${key === 'YOUR_API_KEY' ? 'placeholder' : 'provided value'}`);
